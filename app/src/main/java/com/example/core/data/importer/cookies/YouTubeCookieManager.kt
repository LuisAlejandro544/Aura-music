package com.example.core.data.importer.cookies

import android.content.Context
import android.net.Uri
import com.example.debug.AuraDebugManager
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileOutputStream

/**
 * Aura Music - Gestor de Cookies de YouTube para yt-dlp (Estilo YTDLnis).
 *
 * Rol Arquitectónico:
 * - Permite al usuario de forma 100% opcional importar o pegar cookies de YouTube en formato Netscape.
 * - Suministra el archivo de cookies mediante el flag '--cookies' a yt-dlp para eludir verificaciones de bot,
 *   captchas o restricciones de edad en canciones y videos protegidos.
 * - La funcionalidad viene desactivada por defecto para respetar la privacidad del usuario.
 */
object YouTubeCookieManager {

    private const val TAG = "YouTubeCookieManager"
    private const val PREFS_NAME = "aura_youtube_cookie_prefs"
    private const val KEY_COOKIES_ENABLED = "pref_youtube_cookies_enabled"
    private const val COOKIES_FILE_NAME = "youtube_cookies.txt"

    private fun getPrefs(context: Context) =
        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)

    /**
     * Devuelve el archivo físico donde se persisten las cookies en el sandbox privado de la app.
     */
    fun getCookiesFile(context: Context): File {
        val binDir = File(context.filesDir, "bin")
        if (!binDir.exists()) binDir.mkdirs()
        return File(binDir, COOKIES_FILE_NAME)
    }

    /**
     * Indica si el usuario tiene activado voluntariamente el uso de cookies.
     */
    fun isCookiesEnabled(context: Context): Boolean {
        return getPrefs(context).getBoolean(KEY_COOKIES_ENABLED, false)
    }

    /**
     * Modifica el estado del interruptor de cookies.
     */
    fun setCookiesEnabled(context: Context, enabled: Boolean) {
        getPrefs(context).edit().putBoolean(KEY_COOKIES_ENABLED, enabled).apply()
        AuraDebugManager.logInfo(TAG, "Uso de cookies de YouTube ${if (enabled) "ACTIVADO" else "DESACTIVADO"}")
    }

    /**
     * Verifica si existe un archivo de cookies con contenido válido guardado en disco.
     */
    fun hasValidCookiesFile(context: Context): Boolean {
        val file = getCookiesFile(context)
        return file.exists() && file.length() > 32L
    }

    /**
     * Importa un archivo de cookies desde un URI de SAF (Storage Access Framework).
     */
    suspend fun importCookiesFromUri(context: Context, uri: Uri): Result<Int> = withContext(Dispatchers.IO) {
        try {
            val contentResolver = context.contentResolver
            val inputStream = contentResolver.openInputStream(uri)
                ?: return@withContext Result.failure(IllegalArgumentException("No se pudo leer el archivo seleccionado"))

            val text = inputStream.bufferedReader().use { it.readText() }
            saveCookiesText(context, text)
        } catch (e: Exception) {
            AuraDebugManager.logWarning(TAG, "Error al importar cookies desde URI: ${e.message}")
            Result.failure(e)
        }
    }

    /**
     * Guarda el texto crudo de cookies en formato Netscape HTTP Cookie File.
     */
    suspend fun saveCookiesText(context: Context, rawText: String): Result<Int> = withContext(Dispatchers.IO) {
        try {
            val trimmed = rawText.trim()
            if (trimmed.length < 16) {
                return@withContext Result.failure(IllegalArgumentException("El contenido de cookies está vacío o es demasiado corto."))
            }

            // Normalización: Asegurar cabecera estándar de Netscape si falta
            val finalContent = if (!trimmed.startsWith("# Netscape HTTP Cookie File")) {
                "# Netscape HTTP Cookie File\n# Generated by Aura Music (YTDLnis Style)\n$trimmed"
            } else {
                trimmed
            }

            val targetFile = getCookiesFile(context)
            FileOutputStream(targetFile).use { out ->
                out.write(finalContent.toByteArray(Charsets.UTF_8))
            }

            // Contar cantidad aproximada de cookies presentes
            val cookieCount = finalContent.lines().count { line ->
                val l = line.trim()
                l.isNotEmpty() && !l.startsWith("#") && l.contains("\t")
            }

            setCookiesEnabled(context, true)
            AuraDebugManager.logInfo(TAG, "Cookies de YouTube guardadas con éxito ($cookieCount detectadas, ${targetFile.length()} bytes)")
            Result.success(cookieCount)
        } catch (e: Exception) {
            AuraDebugManager.logWarning(TAG, "Error guardando archivo de cookies: ${e.message}")
            Result.failure(e)
        }
    }

    /**
     * Elimina el archivo de cookies guardado y apaga el interruptor.
     */
    fun clearCookies(context: Context): Boolean {
        return try {
            val file = getCookiesFile(context)
            if (file.exists()) {
                file.delete()
            }
            setCookiesEnabled(context, false)
            AuraDebugManager.logInfo(TAG, "Archivo de cookies eliminado y función desactivada.")
            true
        } catch (e: Exception) {
            AuraDebugManager.logWarning(TAG, "Error eliminando cookies: ${e.message}")
            false
        }
    }
}
